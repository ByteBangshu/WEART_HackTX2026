from typing import Protocol

from .domain import Brief, Classification, Extraction, Research, Verification


class Provider(Protocol):
    async def classify(self, image: bytes, scenario: str, budget) -> Classification: ...
    async def extract(self, image: bytes, scenario: str, budget) -> Extraction: ...
    async def research(self, extraction: Extraction, excluded: list[str], budget) -> Research: ...
    async def synthesize(self, context: dict, budget, repair: bool = False) -> Brief: ...
    async def verify(self, brief: Brief, context: dict, budget) -> Verification: ...
    async def close(self) -> None: ...
